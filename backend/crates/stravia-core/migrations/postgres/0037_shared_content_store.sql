-- 共享正文存储（准备）：Turn Chain、History Marker 与 Interaction Observation 平级使用
-- 同一张按 Principal 隔离、内容寻址的正文表，并按引用判活。
--
-- `turn_scopes` 直接改名；PostgreSQL 会同步更新所有 REFERENCES。`contents` 的既有数据
-- 转换在 0037 与 0038 之间的 Rust 钩子内完成，旧 `turn_contents` 与 `turn_node_contents`
-- 在转换期间仍是权威。0038 完成切换并删除旧表。
ALTER TABLE turn_scopes RENAME TO content_scopes;

CREATE TABLE contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_id BIGINT NOT NULL REFERENCES content_scopes(id) ON DELETE RESTRICT,
    digest BYTEA NOT NULL CHECK(octet_length(digest) = 32),
    format SMALLINT NOT NULL CHECK(format IN (0, 1)),
    raw_len BIGINT NOT NULL CHECK(raw_len >= 0),
    body BYTEA NOT NULL,
    UNIQUE(scope_id, digest),
    UNIQUE(scope_id, id)
);
-- storage codec 已压缩正文；TOAST 只负责外部存储，避免再次尝试压缩。
ALTER TABLE contents ALTER COLUMN body SET STORAGE EXTERNAL;

CREATE TABLE content_gc (
    content_id BIGINT PRIMARY KEY REFERENCES contents(id) ON DELETE CASCADE
);

-- 新引用表在 0038 改名为 turn_node_contents；转换期间与旧表并存。
CREATE TABLE turn_node_contents_v4 (
    node_pk BIGINT NOT NULL,
    scope_id BIGINT NOT NULL,
    ordinal BIGINT NOT NULL CHECK(ordinal >= 0),
    content_id BIGINT NOT NULL,
    PRIMARY KEY(node_pk, ordinal),
    UNIQUE(node_pk, content_id),
    FOREIGN KEY(node_pk, scope_id)
        REFERENCES turn_nodes(node_pk, scope_id) ON DELETE CASCADE,
    FOREIGN KEY(scope_id, content_id)
        REFERENCES contents(scope_id, id) ON DELETE RESTRICT
);
CREATE INDEX turn_node_contents_v4_content_idx ON turn_node_contents_v4(content_id);

CREATE TABLE history_marker_contents (
    reference TEXT NOT NULL REFERENCES history_markers(reference) ON DELETE CASCADE,
    ordinal BIGINT NOT NULL CHECK(ordinal >= 0),
    content_id BIGINT NOT NULL REFERENCES contents(id) ON DELETE RESTRICT,
    PRIMARY KEY(reference, ordinal),
    UNIQUE(reference, content_id)
);
CREATE INDEX history_marker_contents_content_idx ON history_marker_contents(content_id);

CREATE TABLE observation_event_contents (
    sequence BIGINT NOT NULL REFERENCES observation_events(sequence) ON DELETE CASCADE,
    ordinal BIGINT NOT NULL CHECK(ordinal >= 0),
    content_id BIGINT NOT NULL REFERENCES contents(id) ON DELETE RESTRICT,
    PRIMARY KEY(sequence, ordinal)
);
CREATE INDEX observation_event_contents_content_idx ON observation_event_contents(content_id);

CREATE TABLE observation_tool_results (
    sequence BIGINT NOT NULL REFERENCES observation_events(sequence) ON DELETE CASCADE,
    ordinal BIGINT NOT NULL CHECK(ordinal >= 0),
    tool_id TEXT NOT NULL,
    is_error BOOLEAN NOT NULL,
    content_id BIGINT NOT NULL REFERENCES contents(id) ON DELETE RESTRICT,
    PRIMARY KEY(sequence, ordinal)
);
CREATE INDEX observation_tool_results_content_idx ON observation_tool_results(content_id);
CREATE INDEX observation_tool_results_tool_idx ON observation_tool_results(tool_id, sequence);

-- Marker 段载荷改为 storage_codec 编码的外壳；0038 用它替换旧的未压缩 TEXT 列。
ALTER TABLE history_markers ADD COLUMN segment_payload_encoded BYTEA;
ALTER TABLE history_markers ALTER COLUMN segment_payload_encoded SET STORAGE EXTERNAL;

-- 一次性离线重写进度；stage 0 = 节点，1 = Marker，2 = 校验完成。
CREATE TABLE content_upgrade (
    phase INTEGER PRIMARY KEY CHECK(phase = 1),
    stage INTEGER NOT NULL CHECK(stage BETWEEN 0 AND 2),
    last_node_pk BIGINT NOT NULL DEFAULT 0,
    last_marker_reference TEXT
);
